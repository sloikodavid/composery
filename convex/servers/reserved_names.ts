/**
 * Confusables that a name could substitute for a letter, restricted to the
 * ASCII subset `namePattern` allows a name to hold: `1`/`l`, `0`/`o`,
 * `5`/`s`, and the two-letter run `rn`/`m`, per Unicode UTS #39. The input
 * is always ASCII-only because `namePattern` enforces `[a-z0-9-]`, so the
 * full Unicode confusables table is unneeded here.
 */
const confusableFolds: readonly (readonly [string, string])[] = [
	["rn", "m"],
	["1", "l"],
	["0", "o"],
	["5", "s"],
];

function foldConfusables(name: string): string {
	return confusableFolds.reduce(
		(folded, [from, to]) => folded.split(from).join(to),
		name,
	);
}

const trailingDigitsPattern = /[0-9]+$/;

function stripTrailingDigits(name: string): string {
	return name.replace(trailingDigitsPattern, "");
}

/**
 * Normalizes a name for the reserved-name check. Both a claimed name and
 * every reserved entry are normalized before comparison, so `api-key`,
 * `apikey`, `api7`, and `www3` all compare equal to their stem. Folding a
 * confusable before or after stripping a trailing digit run disagrees for
 * some names, such as `paypa1` (fold first, to `paypal`) against `admin0`
 * (strip first, to `admin`), so both orders are returned and either may
 * match.
 */
export function normalizeReservedName(name: string): ReadonlySet<string> {
	const hyphenless = name.replace(/-/g, "");
	return new Set([
		foldConfusables(stripTrailingDigits(hyphenless)),
		stripTrailingDigits(foldConfusables(hyphenless)),
	]);
}

const normalizedReservedNames: ReadonlyMap<string, ReservedNameReason> =
	(() => {
		const byNormalized = new Map<string, ReservedNameReason>();
		for (const reason of Object.keys(reservedNames) as ReservedNameReason[]) {
			for (const entry of reservedNames[reason]) {
				for (const normalized of normalizeReservedName(entry)) {
					if (!byNormalized.has(normalized)) {
						byNormalized.set(normalized, reason);
					}
				}
			}
		}
		return byNormalized;
	})();

/** Finds why a name is reserved, or `null` when it is not. */
export function findReservedNameReason(
	name: string,
): ReservedNameReason | null {
	for (const normalized of normalizeReservedName(name)) {
		const reason = normalizedReservedNames.get(normalized);
		if (reason !== undefined) {
			return reason;
		}
	}
	return null;
}
